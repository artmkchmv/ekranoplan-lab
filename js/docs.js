  function toc() {
    const items = [['labels', 'Что означают метки'], ['forces', 'Подъёмная сила и сопротивление'], ['ge', 'Экранный эффект'], ['endplates', 'Шайбы', true],
      ['wing', 'Крыло конечного размаха'], ['balance', 'Равновесие и устойчивость'], ['motion', 'Полёт планера'], ['power', 'Мощность и дальность'],
      ['limits', 'Ограничения модели'], ['check', 'Проверка по источникам'], ['crafts', 'Данные аппаратов'], ['sources', 'Источники']];

    return items.map(([id, t, sub]) => `<a href="#${id}" data-id="${id}" class="${sub ? 'sub' : ''}">${t}</a>`).join('');
  }

  function build() {
    if (built)
      return;

    built = true;

    const body = document.getElementById('docsBody');
    body.innerHTML = html();

    document.getElementById('docsToc').innerHTML = toc();

    const opts = { throwOnError: false };

    body.querySelectorAll('[data-tex]').forEach(el => { if (window.katex) katex.render(el.dataset.tex, el, Object.assign({ displayMode: true }, opts)); else el.textContent = el.dataset.tex; });
    body.querySelectorAll('[data-itex]').forEach(el => { if (window.katex) katex.render(el.dataset.itex, el, opts); else el.textContent = el.dataset.itex; });

    const links = [...document.querySelectorAll('#docsToc a')];

    const targets = links.map(a => document.getElementById(a.dataset.id)).filter(Boolean);

    let queued = false, curId = null;

    const spy = () => {
      queued = false;
      if (document.getElementById('docs').hidden)
        return;

      let cur = targets[0];

      targets.forEach(t => { if (t.getBoundingClientRect().top < innerHeight * 0.3) cur = t; });

      if (!cur || cur.id === curId)
        return;

      curId = cur.id;

      links.forEach(a => a.classList.toggle('on', a.dataset.id === curId));
    };

    window.addEventListener('scroll', () => { if (!queued) { queued = true; requestAnimationFrame(spy); } }, { passive: true });

    spy();
  }

  return { build };
